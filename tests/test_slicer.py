"""Slice pipeline tests.

The metadata parser is tested against a fixture that reproduces PrusaSlicer's real
layout — in particular the fact that the interesting comments sit *before* the
several-hundred-line config block, not at the end of the file. A parser that reads
the tail passes a naive test and fails on real output.
"""

from __future__ import annotations

import shutil

import pytest

from vtp.config import slicer_profile
from vtp.slicer import SliceResult, SlicerError, _parse_duration, slice_stl

pytestmark = pytest.mark.filterwarnings("ignore::DeprecationWarning")

REAL_SLICER = shutil.which("prusa-slicer") is not None

#: Trimmed from real 2.9.4 output for box_with_lid_body.stl: three layer markers,
#: the metadata block, then the config block that follows it in a real file.
FIXTURE_GCODE = """\
; generated by PrusaSlicer 2.9.4+UNKNOWN
M190 S60
G28 ; home all axis
G29 ; auto bed levelling
;LAYER_CHANGE
;Z:0.2
G1 X10 Y10 E1.0
;LAYER_CHANGE
;Z:0.4
G1 X20 Y20 E2.0
;LAYER_CHANGE
;Z:0.6
G1 X30 Y30 E3.0
M107 ; turn off fan
M84 X Y E ; disable motors
; filament used [mm] = 1426.18
; filament used [cm3] = 3.43
; filament used [g] = 4.25
; filament cost = 0.09
; total filament used [g] = 4.25
; estimated printing time (normal mode) = 30m 44s
; estimated first layer printing time (normal mode) = 2m 39s

; prusaslicer_config = begin
; layer_height = 0.2
; filament used [g] = 999.99
; z_offset = 0
; prusaslicer_config = end
"""


def write_gcode(tmp_path, text=FIXTURE_GCODE, name="part.gcode"):
    path = tmp_path / name
    path.write_text(text, encoding="utf-8")
    return path


def fake_slice(tmp_path, monkeypatch, gcode_text=FIXTURE_GCODE, returncode=0):
    """Stub PrusaSlicer: write the fixture where --output says, then exit."""
    import subprocess

    stl = tmp_path / "part.stl"
    stl.write_bytes(b"solid x\nendsolid x\n")

    def run(command, **kwargs):
        target = command[command.index("--output") + 1]
        if returncode == 0:
            with open(target, "w", encoding="utf-8") as fh:
                fh.write(gcode_text)
        return subprocess.CompletedProcess(command, returncode, "progress 90%", "")

    monkeypatch.setattr(subprocess, "run", run)
    monkeypatch.setattr("vtp.slicer.shutil.which", lambda _: "/usr/bin/prusa-slicer")
    return stl


