def test_captures_child_output_rather_than_inheriting_it(tmp_path, monkeypatch):
    """PrusaSlicer prints progress to stdout; under stdio transport that stream is
    JSON-RPC. Inheriting it would corrupt the protocol."""
    import subprocess

    seen = {}
    stl = tmp_path / "part.stl"
    stl.write_bytes(b"solid x\nendsolid x\n")
    monkeypatch.setattr("vtp.slicer.shutil.which", lambda _: "/usr/bin/prusa-slicer")

    def run(command, **kwargs):
        seen.update(kwargs)
        target = command[command.index("--output") + 1]
        with open(target, "w", encoding="utf-8") as fh:
            fh.write(FIXTURE_GCODE)
        return subprocess.CompletedProcess(command, 0, "", "")

    monkeypatch.setattr(subprocess, "run", run)
    slice_stl(stl, output=tmp_path / "p.gcode")
    assert seen["capture_output"] is True


