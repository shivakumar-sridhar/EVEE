def test_oversized_part_is_refused_before_the_slicer_runs(tmp_path, monkeypatch):
    """PrusaSlicer rejects it too, but names neither the axis nor the overshoot."""
    import subprocess

    from vtp.cad import design

    designed = design(
        "box_with_lid",
        {"outer_l": 400.0, "outer_w": 30.0, "outer_h": 15.0},
        output_dir=tmp_path,
        render=False,
    )

    def explode(*args, **kwargs):
        raise AssertionError("the slicer must not be invoked for an oversized part")

    monkeypatch.setattr(subprocess, "run", explode)

    with pytest.raises(SlicerError, match=r"X is 400mm .* limit is 220mm"):
        slice_stl(designed.stl_paths["body"], output=tmp_path / "big.gcode")


