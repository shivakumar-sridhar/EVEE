@pytest.mark.parametrize(
    "text,seconds",
    [
        ("30m 44s", 1844),
        ("44s", 44),
        ("1h 2m 3s", 3723),
        ("2d 4h 30m 10s", 189010),
        ("30m44s", 1844),  # no space — older output
    ],
)
def test_duration_parses(text, seconds):
    assert _parse_duration(text) == seconds


def test_duration_rejects_nonsense_naming_the_value():
    with pytest.raises(SlicerError, match="soon"):
        _parse_duration("soon")


