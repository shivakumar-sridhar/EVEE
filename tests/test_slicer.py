@pytest.mark.skipif(not REAL_SLICER, reason="prusa-slicer not installed")
def test_acceptance_slices_the_verified_part(tmp_path):
    """Phase 2 acceptance: the Phase 1 STL slices, and its metadata matches the
    physically verified print — 55 layers, 4.25 g, 30m 44s."""
    from vtp.cad import design

    designed = design(
        "box_with_lid",
        {
            "outer_l": 30.6,
            "outer_w": 27.7,
            "outer_h": 11.0,
            "ports": [
                {"side": "left", "width": 9.0, "height": 5.5},
                {"side": "right", "width": 9.0, "height": 5.5},
            ],
        },
        output_dir=tmp_path,
        render=False,
    )

    result = slice_stl(designed.stl_paths["body"], output=tmp_path / "body.gcode")
    assert result.profile == slicer_profile()
    assert result.layer_count == 55
    assert result.filament_g == pytest.approx(4.25, abs=0.1)
    assert result.print_time_seconds == pytest.approx(1844, abs=120)
    assert result.gcode_path.stat().st_size > 0


