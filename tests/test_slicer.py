@pytest.mark.parametrize("count", [0, 2])
def test_a_missing_or_doubled_anchor_is_left_alone(
    tmp_path, monkeypatch, isolated_mesh_state, count
):
    """If the profile changed underneath us, guessing which line was meant is worse."""
    store_mesh(isolated_mesh_state)
    text = FIXTURE_GCODE.replace(
        "G29 ; auto bed levelling\n", "G29 ; auto bed levelling\n" * count
    )
    stl = fake_slice(tmp_path, monkeypatch, gcode_text=text)
    result = slice_stl(stl, output=tmp_path / "out.gcode")

    assert result.levelling == "probe"
    assert f"found {count}" in result.levelling_detail
    assert result.gcode_path.read_text() == text


def test_the_rewrite_leaves_no_temp_file_behind(
    tmp_path, monkeypatch, isolated_mesh_state
):
    """A half-written G-code must never be something a human can upload."""
    store_mesh(isolated_mesh_state)
    stl = fake_slice(tmp_path, monkeypatch)
    slice_stl(stl, output=tmp_path / "out.gcode")

    assert list(tmp_path.glob("*.tmp")) == []


def test_the_swap_does_not_disturb_the_metadata(
    tmp_path, monkeypatch, isolated_mesh_state
):
    """Gate 2's numbers describe the file that gets uploaded, swap or no swap."""
    stl = fake_slice(tmp_path, monkeypatch)
    probed = slice_stl(stl, output=tmp_path / "a.gcode")

    store_mesh(isolated_mesh_state)
    stored = slice_stl(stl, output=tmp_path / "b.gcode")

    assert stored.levelling == "stored"
    assert (stored.layer_count, stored.filament_g, stored.print_time_seconds) == (
        probed.layer_count,
        probed.filament_g,
        probed.print_time_seconds,
    )
    assert "stored mesh" in stored.summary()
